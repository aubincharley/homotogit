def catalogue_table(cfg):
    from build_catalogue import ORDER, num, tex as ltex
    rows = []
    for eid in ORDER:
        g = cfg[cfg.experiment == eid]
        if g.empty:
            continue
        head = g.iloc[0]
        rows.append(r"\multicolumn{5}{@{}p{\linewidth}@{}}{\rule{0pt}{2.8ex}\textbf{%s}}\\*"
                    % ltex(head.experiment_title))
        rows.append(r"\multicolumn{5}{@{}p{\linewidth}@{}}{\footnotesize %s}\\*" % ltex(
            "%s. Evaluation split: %s. Timing: %s." % (str(head.conditions).rstrip("."),
                                                       head.evaluation_split or "n/a",
                                                       head.timing_scope)))
        for r in g.itertuples():
            label = r.label + (" (diverged)" if r.status != "valid" else "")
            if isinstance(r.flags, str) and r.flags:
                label += " (%s)" % r.flags.replace(";", ", ")
            rows.append("%s & %s & %s & %d/%d & %s\\\\" % (
                ltex(label), num(r.acc_mean), num(r.acc_sd), r.seeds_valid, r.seeds_attempted,
                "---" if pd.isna(r.wall_seconds_mean) else "%.0f" % r.wall_seconds_mean))
    tex("catalogue_compact", r"""\begingroup\small
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{4.05in}rrcr@{}}
\caption{Historical configuration catalogue, recomputed from the per-run records. Accuracy is the
final recorded evaluation of each run, averaged over its numerically valid seeds, in percent; SD is
the sample SD over those seeds in percentage points, absent with a single valid seed. Seeds are
valid/attempted, so diverged runs stay visible. Wall time is the mean over valid runs on the timing
scope of the group heading. Groups differ in data, budget and evaluation split, so rows are
comparable only within a group.}\label{tab:catalogue}\\
\toprule Configuration & Acc.\ (\%) & SD & Seeds & Wall (s)\\\midrule\endfirsthead
\toprule Configuration & Acc.\ (\%) & SD & Seeds & Wall (s)\\\midrule\endhead
\midrule\multicolumn{5}{r}{Continued on next page}\\\endfoot
\bottomrule\endlastfoot
""" + "\n".join(rows) + "\n" + r"\end{longtable}\endgroup")


