# --------------------------------------------------------------------- prose macros

def macro(name, value):
    return "\\newcommand{\\%s}{%s}" % (name, value)


def numbers(S, large_paired, hess, endpoints, bars, pca, cells, trans, f64, hvp):
    L = ["% Numbers quoted in the prose, so text and tables cannot drift apart."]
    res = S[S.method == "resolution_max_b1"]
    L += [macro("tSettings", S.setting.nunique()),
          macro("tResPositiveSettings", int((res.gain_mean > 0).sum())),
          macro("tResPositivePairs", int(res.n_seeds_gain_positive.sum())),
          macro("tResPairs", int(res.n_seeds.sum())),
          macro("tResGainMin", "%.2f" % res.gain_mean.min()),
          macro("tResGainMax", "%.2f" % res.gain_mean.max())]
    for key, st in (("Stl", "stl10"), ("SubShort", "cifar10_5k/stl_budget"),
                    ("SubLong", "cifar10_5k/reference_updates")):
        g = S[(S.setting == st) & (S.method == "resolution_max_b1_gaussian_conv")].iloc[0]
        L += [macro("tRG%sGain" % key, "%.2f" % abs(g.gain_mean)),
              macro("tRG%sSeeds" % key, int(g.n_seeds_gain_positive))]
    g = S[S.setting == "sgd"].set_index("method")
    for m in M:
        L += [macro("tSgd%sAcc" % NAME[m], "%.2f" % g.loc[m].test_acc_mean),
              macro("tSgd%sAccSD" % NAME[m], "%.2f" % g.loc[m].test_acc_sd),
              macro("tSgd%sMinutes" % NAME[m], "%.1f" % g.loc[m].wall_minutes_mean)]
    gn = S[S.setting == "resnet20gn_cifar10"].set_index("method")
    stl = S[S.setting == "stl10"].set_index("method")
    for tag, src in (("Gn", gn), ("Stl", stl)):
        for m in ("plain", "resolution_max_b1"):
            L += [macro("t%s%sTrainCE" % (tag, NAME[m]), "%.3f" % src.loc[m].train_probe_ce_mean),
                  macro("t%s%sTestCE" % (tag, NAME[m]), "%.3f" % src.loc[m].test_ce_mean)]
    e = endpoints.groupby("method")
    for m in M:
        L += [macro("tLand%sTrainCE" % NAME[m], "%.3f" % e.get_group(m).train_full_ce.mean()),
              macro("tLand%sTestCE" % NAME[m], "%.3f" % e.get_group(m).test_full_ce.mean())]
