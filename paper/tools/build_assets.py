def save(fig, name: str):
    FIG.mkdir(parents=True, exist_ok=True)
    for fmt in ("pdf", "png"):
        buf = io.BytesIO()
        fig.savefig(buf, format=fmt, dpi=180, bbox_inches="tight")
        payload = buf.getvalue()
        buf.close()
        dst = FIG / ("%s.%s" % (name, fmt))
        tmp = dst.with_suffix(".%s.tmp" % fmt)
        with open(tmp, "wb") as fh:
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        tmp.replace(dst)
    plt.close(fig)
    print("wrote figures/%s.pdf (+png)" % name)


def tex(name: str, body: str):
    TAB.mkdir(parents=True, exist_ok=True)
    head = ("% GENERATED by paper/tools/build_assets.py from data/records/ -- do not edit by hand.\n"
            "% Regenerate: py paper/tools/build_records.py && py paper/tools/build_assets.py\n")
    (TAB / (name + ".tex")).write_text(head + body.strip() + "\n", encoding="utf-8")
    print("wrote tables/%s.tex" % name)


def pm(a, b, d=2, sign=False):
    if pd.isna(a):
        return "---"
    if pd.isna(b):
        return ("$%+.*f$" if sign else "$%.*f$") % (d, a)
    return ("$%+.*f\\pm%.*f$" if sign else "$%.*f\\pm%.*f$") % (d, a, d, b)


def thousands(v) -> str:
    return "{:,}".format(int(round(float(v)))).replace(",", "\\,")


def sig(a, b, digits=3) -> str:
    """Mean and SD to a fixed number of significant digits of the mean.

    Training-probe cross-entropies span four orders of magnitude between settings, so a
    fixed number of decimals would print several of them as zero.
    """
    if pd.isna(a):
        return "---"
    exp = 0 if a == 0 else int(np.floor(np.log10(abs(a))))
    d = max(0, digits - 1 - exp)
    return "$%.*f\\pm%.*f$" % (d, a, d, 0 if pd.isna(b) else b)


