def blocks_body(row_fn, ncols, keep=None):
    out = []
    for title, rows in BLOCKS:
        rows = [(lab, st) for lab, st in rows if keep is None or st in keep]
        if not rows:
            continue
        out.append("\\multicolumn{%d}{@{}p{\\linewidth}@{}}{\\rule{0pt}{2.6ex}\\textit{%s}}\\\\"
                   % (ncols, title))
        out += [row_fn(lab, st) for lab, st in rows]
        out.append("\\addlinespace[3pt]")
    return "\n".join(out[:-1])


