"""Stage 2 of the asset pipeline: tidy records -> tables, figures and prose macros.

    py paper/tools/build_assets.py

Reads only ``data/records/*.csv`` (written by ``build_records.py`` from the original
experiment records) and writes ``tables/*.tex``, ``tables/numbers_generated.tex``,
``figures/*.pdf`` with a ``.png`` preview, and ``evidence/RECOMPUTED_CHECKS.json``.
Nothing here loads a network, trains or evaluates a model.

Conventions of every table and figure written here:

* a value is the final scheduled epoch of a run, never a best-epoch selection;
* ``mean +/- SD`` is the mean and the sample standard deviation across *training
  seeds* of one setting; it is not a confidence interval, and it is absent when a
  setting has a single seed;
* paired gains and paired differences are formed within a seed and averaged
  afterwards; repeated perturbation directions are not replications;
* units are named in the column header: percent, percentage points, nats, minutes;
* a fact shared by every row of a block is printed once in the block heading, and a
  fact that varies is printed in the row, so no row depends on a distant reference.
"""
