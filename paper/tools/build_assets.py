def fig_sensitivity(paired):
    for policies, name in ((["saved", "recalibrated"], "sensitivity_summary"),
                           (["centre_frozen"], "sensitivity_centre_frozen")):
        fig, axes = plt.subplots(len(policies), 2, figsize=(7.0, 2.7 * len(policies) + .3),
                                 squeeze=False, layout="constrained")
        for i, pol in enumerate(policies):
            for j, split in enumerate(("train_probe", "test_probe")):
                ax = axes[i, j]
                ax.axhline(0, color="#555555", lw=.8)
                for m in M[1:]:
                    g = paired[(paired.policy == pol) & (paired.split == split)
                               & (paired.method == m)].sort_values("amplitude")
                    x = g.amplitude.to_numpy()
                    y = g.mean_delta.to_numpy()
                    sd = g.sd_delta.to_numpy()
                    assert len(x) == 10
                    ax.plot(x, y, "o-", ms=3.2, lw=1.4, color=COLOR[m], label=LONG[m])
                    ax.fill_between(x, y - sd, y + sd, color=COLOR[m], alpha=.13, lw=0)
                ax.set_xscale("log")
                ax.set_xticks([.005, .01, .025, .05, .1, .25, .5],
                              [".005", ".01", ".025", ".05", ".1", ".25", ".5"])
                ax.tick_params(axis="x", labelsize=8)
